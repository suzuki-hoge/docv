//! docv build が document_root の直下に書くインデックス（README.md）。docv/slot/service/service/html.md の「インデックス」。
//!
//! GitHub でリポジトリを開いた人が、clone しなくても Slot ファイルを読めるように、
//! HTML の Slot のページ（index.html）と同じ順に、元のファイルへのリンクを並べる。
//! GitHub はシンボリックリンクの先を表示しないので、エイリアスやコピーは置かず、Markdown のリンクで辿らせる。

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Result, bail};

use crate::build;
use crate::decision::Kind;
use crate::markdown::relative_path;
use crate::slot::{Content, DEFS, Group, Slot};
use crate::workspace::Project;

/// インデックスの 1 行目。docv が作ったことを示す。これで始まらない同じ名前のファイルは書き換えない。
const MARKER: &str = "<!-- docv build が作るファイル。手で書き換えず、docv build で作り直す -->";

/// インデックスのパス。build のたびに書く。
pub fn path(project: &Project) -> PathBuf {
    project.index_path()
}

/// インデックスの末尾。作った docv の版を書き、手で直すファイルではないと GitHub で見ても分かるようにする。
pub fn generated_by() -> String {
    format!("Generated by docv {}", env!("CARGO_PKG_VERSION"))
}

/// path に書いてよいか。docv が作った印のない、同じ名前のファイルがあれば error。
/// 手で書いたファイルを消さないため。build は、出力先に何か書く前にこれを確かめる。
pub fn ensure_writable(path: &Path) -> Result<()> {
    if !path.exists() {
        return Ok(());
    }
    let text = fs::read_to_string(path).unwrap_or_default();
    if text.lines().next() != Some(MARKER) {
        bail!(
            "{} は docv が作ったファイルではないので書けない",
            path.display()
        );
    }
    Ok(())
}

/// インデックスに並べる Slot の 1 行。分けた Slot は、Slot の名前の下に、ページを order の順に並べる。
pub enum Item<'a> {
    Single(&'static str, &'a Slot),
    Split(&'static str, Vec<(&'a str, &'a Slot)>),
}

/// インデックスに並べる Slot を、まとまりごとに DEFS の順で返す。置いていない Slot と、include に当てはまらない Slot は出さない。
/// Slot がなくなったまとまりは出さない。GitHub で見るインデックスと、HTML の Index のページで、同じ並びにする。
pub fn outline<'a>(
    slots: &'a [Slot],
    include: impl Fn(&Slot) -> bool,
) -> Vec<(Group, Vec<Item<'a>>)> {
    let mut groups = Vec::new();
    for group in Group::ALL {
        let mut items = Vec::new();
        for def in DEFS.iter().filter(|d| d.group == group) {
            let members: Vec<&Slot> = slots
                .iter()
                .filter(|s| s.def.id == def.id && include(s))
                .collect();
            let Some(first) = members.first() else {
                continue;
            };
            if first.page.is_some() {
                let pages = members
                    .iter()
                    .map(|slot| {
                        let title = slot.page.as_ref().map_or(def.label, |p| p.title.as_str());
                        (title, *slot)
                    })
                    .collect();
                items.push(Item::Split(def.label, pages));
            } else {
                items.push(Item::Single(def.label, first));
            }
        }
        if !items.is_empty() {
            groups.push((group, items));
        }
    }
    groups
}

/// インデックスの中身。index は書く先のパスで、リンクはそのディレクトリからの相対パスにする。
/// Slot は、HTML の Slot のページ（index.html）と同じく、まとまりごとに DEFS の順で並べる。置いていない Slot は出さない。
/// md の Slot は元のファイルへ、YAML の Slot は generate.image が true なら JPG へリンクし、false なら出さない。分けた Slot のページも同じ。
/// JPG を出すかは、generate.image で決める。--no-image で build しても、同じインデックスになる。
/// Free ファイル、ADR、PDR は、置いているディレクトリと、HTML で見るときのページを示す。
/// kinds は、決定がある記録の種類（ADR、PDR）。
pub fn render(
    project: &Project,
    index: &Path,
    slots: &[Slot],
    has_free: bool,
    kinds: &[Kind],
) -> String {
    let from = index.parent().unwrap_or(&project.root);
    let image_dir = project.image_dir();
    let link = |label: &str, target: &Path| {
        format!(
            "[{}](<{}>)",
            escape_label(label),
            relative_path(from, target)
                .replace('<', "%3C")
                .replace('>', "%3E")
        )
    };

    let mut out = format!(
        "{MARKER}\n\n# {}\n\n本ページは、プロジェクトをローカルに取得しなくても、GitHub などのホスティングサービス上で docv のビジュアライズページとほぼ同じ内容を閲覧するためのもの。\n",
        project.title()
    );
    // md の Slot は元のファイル、YAML の Slot は JPG。generate.image が false なら、YAML の Slot はリンクしない。
    let target = |slot: &Slot| -> Option<PathBuf> {
        if matches!(slot.content, Content::Markdown(_)) {
            Some(source(project, slot))
        } else {
            image_dir
                .as_ref()
                .map(|dir| dir.join(build::jpg_path(slot)))
        }
    };
    for (group, items) in outline(slots, |slot| target(slot).is_some()) {
        let mut lines = Vec::new();
        for item in items {
            match item {
                Item::Single(label, slot) => {
                    if let Some(to) = target(slot) {
                        lines.push(format!("- {}", link(label, &to)));
                    }
                }
                Item::Split(label, pages) => {
                    lines.push(format!("- {label}"));
                    for (title, slot) in pages {
                        if let Some(to) = target(slot) {
                            lines.push(format!("  - {}", link(title, &to)));
                        }
                    }
                }
            }
        }
        let _ = write!(out, "\n## {}\n\n{}\n", group.label(), lines.join("\n"));
    }
    // Free ファイル、ADR、PDR は、ディレクトリへのリンクと、HTML で見るときのページを案内する。
    // ページのパスは、docv open と同じく、ルートで開く前提のルートからのパスで示す。
    let html = |page: &str| format!("{}/{page}", project.config.html_dir());
    if has_free {
        let dir = project.config.free_dir();
        let _ = write!(
            out,
            "\n## Free ファイル\n\n- {} ディレクトリを参照\n\n検索やタグでの絞り込みをしたい場合は、リポジトリを取得し `docv open` するもしくは直接 `{}` を開いてください。\n",
            link(&dir, &project.root.join(&dir)),
            html(build::DETAIL_PAGE)
        );
    }
    for kind in kinds {
        let dir = crate::decision::dir(project, *kind);
        let _ = write!(
            out,
            "\n## {label}\n\n- {} ディレクトリを参照\n\n{label} の系譜をたどりたい場合は、リポジトリを取得し `docv open` するもしくは直接 `{}` を開いてください。\n",
            link(&dir, &project.root.join(&dir)),
            html(build::decision_index_page(*kind)),
            label = kind.label(),
        );
    }
    let _ = write!(out, "\n---\n\n{}\n", generated_by());
    out
}

/// Slot ファイルの、リンクに使うパス。シンボリックリンクなら、ルートの中にある先のファイルにする。
/// GitHub は、シンボリックリンクを開いても先の中身を表示しないため。
fn source(project: &Project, slot: &Slot) -> PathBuf {
    let path = project.root.join(&slot.path);
    match fs::canonicalize(&path) {
        Ok(real) if real.starts_with(&project.root) => real,
        _ => path,
    }
}

/// リンクの文字の、Markdown として意味を持つ角括弧とバックスラッシュを escape する。
fn escape_label(label: &str) -> String {
    let mut out = String::new();
    for c in label.chars() {
        if matches!(c, '[' | ']' | '\\') {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

