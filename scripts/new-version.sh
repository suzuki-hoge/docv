#!/bin/bash
# 版を上げる。人間が make new-version V=x.y.z で実行する（docv/slot/operation/release.md）
# 版の書き換え、make fix、「版を x.y.z にする」のコミット、タグ、push までを行う
# 版を書く場所が増えたり、書き方が変わったりしたら、targets か KEEP を直す
# macOS の /bin/bash（3.2）で動くように書く
set -euo pipefail

cd "$(git rev-parse --show-toplevel)"

SCRIPT=scripts/new-version.sh
GUIDE=assets/update-guide.yaml

# 版を書き換える場所。{v} が版に当たる。どれも、古い版でちょうど 1 か所に当たること
targets() {
    "$1" Cargo.toml $'\nname = "docv"\nversion = "{v}"\n'
    "$1" Cargo.lock $'\nname = "docv"\nversion = "{v}"\n'
    "$1" docv.yaml $'\ndocv_version: {v}\n'
    "$1" docv/slot/service/service/config.md '/suzuki-hoge/docv/v{v}/assets/schema/'
    "$1" docv/slot/service/service/config.md $'\ndocv_version: {v}\n'
}

# 書き換えた後も、古い版が残ってよい場所（git grep の除外）
KEEP=(
    ":!$GUIDE"         # 版ごとの変更点。過去の版も書く
    ':!Cargo.lock'     # ほかのクレートの版。docv の版は targets で書き換える
    ':!docv/adr'       # 決めたときの記録
    ':!docv/pdr'       # 決めたときの記録
    ':!docv/README.md' # make fix で作り直す
    ':!output'         # make fix で作り直す
)

stage=check

say() { printf '==> %s\n' "$*"; }

fail() {
    printf 'new-version: %s\n' "$@" >&2
    exit 1
}

# $1 の版が、$2 の版より新しいか
newer() {
    local a b i
    IFS=. read -r -a a <<<"$1"
    IFS=. read -r -a b <<<"$2"
    for i in 0 1 2; do
        if ((a[i] != b[i])); then
            ((a[i] > b[i]))
            return
        fi
    done
    return 1
}

# ファイル $1 に、文字列 $2 がいくつあるか
count() {
    TEXT="$2" perl -0777 -ne 'my $n = () = /\Q$ENV{TEXT}\E/g; print $n' "$1"
}

check_target() {
    local file=$1 text=${2//'{v}'/$OLD} n
    [[ -f $file ]] || fail "$file がない" "版を書く場所が変わったので、$SCRIPT の targets を直す"
    n=$(count "$file" "$text")
    if [[ $n != 1 ]]; then
        fail "$file で、古い版を書いた次の文字列が $n か所に当たった（1 か所のはず）" "$text" \
            "版の書き方が変わったので、$SCRIPT の targets を直す"
    fi
}

apply_target() {
    local file=$1 from=${2//'{v}'/$OLD} to=${2//'{v}'/$NEW}
    FROM="$from" TO="$to" perl -0777 -i -pe 's/\Q$ENV{FROM}\E/$ENV{TO}/' "$file"
}

target_files=()
collect_target() { target_files+=("$1"); }

# 版上げで変わってよいファイルか
expected_change() {
    local path=$1 file
    case $path in
    "$GUIDE" | docv/README.md | output/*) return 0 ;;
    esac
    for file in "${target_files[@]}"; do
        [[ $path == "$file" ]] && return 0
    done
    return 1
}

changed_paths() {
    git -c core.quotePath=false status --porcelain=v1 -uall | cut -c4-
}

# 書き換えを始めた後に止まったら、update-guide.yaml のほかを元に戻す
on_exit() {
    local status=$?
    if [[ $status != 0 && $stage == change ]]; then
        printf 'new-version: 書き換えを元に戻す（%s はそのまま）\n' "$GUIDE" >&2
        git restore --source=HEAD --staged --worktree -- . ":!$GUIDE"
        if [[ $(docv --version 2>/dev/null || true) == "docv $NEW" ]]; then
            printf 'new-version: install した docv を %s に戻す\n' "$OLD" >&2
            cargo install -q --path .
        fi
    fi
}
trap on_exit EXIT

# 1. 始める前に確かめる。ここで止まれば、何も書き換えていない

[[ $# == 1 && -n $1 ]] || fail "版を渡す。例: make new-version V=2.2.0"
NEW=$1
[[ $NEW =~ ^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$ ]] || fail "版は x.y.z の形で渡す（例: 2.2.0）。渡したのは $NEW"

OLD=$(awk -F'"' '/^version = / { print $2; exit }' Cargo.toml)
[[ $OLD =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || fail "Cargo.toml から今の版を読めない"
newer "$NEW" "$OLD" || fail "$NEW が、今の版 $OLD より新しくない"

say "$OLD を $NEW に上げる"

[[ $(git symbolic-ref --short -q HEAD || true) == main ]] || fail "main で実行する"

others=$(changed_paths | grep -v -x -F "$GUIDE" || true)
[[ -z $others ]] || fail "$GUIDE のほかに変更がある。コミットするか戻してから実行する" "$others"

top=$(awk '/^- version: / { print $3; exit }' "$GUIDE")
[[ $top == "$NEW" ]] || fail "$GUIDE の先頭の版が $top になっている。先頭に $NEW の変更点と対応を書いてから実行する"

if git rev-parse -q --verify "refs/tags/v$NEW" >/dev/null; then
    fail "タグ v$NEW が手元にもうある"
fi
git fetch -q origin main
git merge-base --is-ancestor origin/main HEAD || fail "origin の main に、手元にないコミットがある。取り込んでから実行する"
if git ls-remote --exit-code --tags origin "refs/tags/v$NEW" >/dev/null; then
    fail "タグ v$NEW が origin にもうある"
fi

targets check_target
targets collect_target

# 2. 版を書き換える

stage=change
say "版を書き換える"
targets apply_target

# 3. 古い版が、残ってよい場所の外に残っていないかを探す

say "古い版 $OLD の残りを探す"
pattern="(^|[^0-9.])${OLD//./\\.}([^0-9]|\$)"
left=$(git grep -n -E "$pattern" -- . "${KEEP[@]}" || true)
if [[ -n $left ]]; then
    fail "古い版 $OLD が残っている" "$left" \
        "版を書く場所なら $SCRIPT の targets に、残してよい場所なら KEEP に足す"
fi

# 4. make fix で確かめ、出力を新しい版で作り直す

say "make fix"
make --no-print-directory fix

if git grep -q -F "Generated by docv $OLD" -- output docv/README.md; then
    fail "出力に古い版 $OLD が残っている。make fix で作り直せていない"
fi
unexpected=$(changed_paths | while IFS= read -r path; do
    expected_change "$path" || printf '%s\n' "$path"
done)
[[ -z $unexpected ]] || fail "版上げのほかの変更が出た" "$unexpected" "make fix で直ったものなら、別にコミットしてから実行する"

# 5. コミットし、タグを打ち、push する

git add -A
git commit -q -m "版を $NEW にする"
stage=commit
git tag "v$NEW"
say "「版を $NEW にする」をコミットし、タグ v$NEW を打った"

say "main とタグ v$NEW を push する"
git push --atomic origin main "v$NEW" ||
    fail "push できなかった。コミットとタグは手元にある。直してから次を実行する" "git push --atomic origin main v$NEW"

say "v$NEW を出した"
